"""这是什么：fleet service——用户级开机自启（P4/P6 交付面）。
不写注册表、不用 schtasks（ONLOGON 需管理员，与安装器 PrivilegesRequired=lowest 冲突），
只往当前用户 Startup 目录放/删一个 .cmd：登录后最小化窗口跑 `fleet up --open`（含 watchdog）。
怎么用：
    fleet service install      安装自启（写 %APPDATA%\\...\\Startup\\AideanFleet.cmd）
    fleet service uninstall    移除自启
    fleet service status       查看安装状态与路径
要点：仅当前用户可见、无需管理员权限；重复 install 覆盖旧脚本（幂等）。
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

SERVICE_NAME = "AideanFleet.cmd"


def startup_dir() -> Path:
    """当前用户 Startup 目录（shell:startup；仅当前用户，免管理员）。"""
    appdata = os.environ.get("APPDATA")
    if not appdata:
        raise RuntimeError("APPDATA 环境变量缺失（用户级自启仅支持 Windows）")
    return Path(appdata) / "Microsoft" / "Windows" / "Start Menu" / "Programs" / "Startup"


def _script_content() -> str:
    """自启脚本内容：纯 ASCII（规避 .cmd 编码问题），最小化窗口启动，watchdog 默认开。"""
    py = sys.executable.replace("\\", "/")
    return (
        "@echo off\r\n"
        "rem AideanFleet autostart (generated by: fleet service install)\r\n"
        "rem remove with: fleet service uninstall\r\n"
        "set FLEET_WATCHDOG=1\r\n"
        f'start "AideanFleet" /min "{py}" -m fleet.cli.main up --open\r\n'
    )


def install() -> dict:
    """安装自启：写 Startup/AideanFleet.cmd（幂等，覆盖旧脚本）。"""
    target = startup_dir() / SERVICE_NAME
    target.parent.mkdir(parents=True, exist_ok=True)
    existed = target.exists()
    target.write_text(_script_content(), encoding="ascii")
    return {"installed": True, "path": str(target), "overwritten": existed}


def uninstall() -> dict:
    """移除自启脚本；未安装时返回 removed=False（幂等）。"""
    target = startup_dir() / SERVICE_NAME
    if not target.exists():
        return {"installed": False, "removed": False, "path": str(target),
                "reason": "未安装（无自启脚本）"}
    target.unlink()
    return {"installed": False, "removed": True, "path": str(target)}


def status() -> dict:
    target = startup_dir() / SERVICE_NAME
    return {"installed": target.exists(), "path": str(target)}
