#!/usr/bin/env python3
"""contracts_gen —— 契约唯一源 → 前端 types.ts 生成器（TASK-001，ADR-002）。

唯一源：packages/contracts/**/*.json（JSON Schema 2020-12 子集）。
输出：fleet/console/web/src/api/types.ts（首行 GENERATED 标记）。
零依赖：只用标准库 json/pathlib/re/argparse。

子集关键字：type / properties / required / enum / items / additionalProperties /
minLength / maxLength / minimum / maximum / pattern / const / $ref（仅本目录内相对引用）。
--check：重新生成并与提交内容比对，不一致退出码 1（守门用）。
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTRACTS = ROOT / "packages" / "contracts"
OUT_FILE = ROOT / "fleet" / "console" / "web" / "src" / "api" / "types.ts"
GENERATED_HEADER = "/* GENERATED by scripts/contracts_gen.py — DO NOT EDIT. 唯一源: packages/contracts */"

_LEGACY_REEXPORT = "export * from './types.legacy'"


def load_contracts() -> dict[str, dict]:
    data: dict[str, dict] = {}
    for path in sorted(CONTRACTS.rglob("*.json")):
        rel = path.relative_to(CONTRACTS).as_posix()
        data[rel] = json.loads(path.read_text(encoding="utf-8"))
    return data


def resolve_ref(ref: str, source_file: str, contracts: dict[str, dict]) -> tuple[str, dict]:
    """解析 $ref，返回 (类型名, schema)。引用必须在 contracts 目录内（相对引用按同目录解析）。"""
    file_part, _, frag = ref.partition("#")
    if file_part:
        target_file = file_part
        if target_file not in contracts:
            # 相对引用：相对引用方所在目录（如 schemas/x.json 内的 plan.json → schemas/plan.json）
            source_dir = source_file.rsplit("/", 1)[0] if "/" in source_file else ""
            joined = f"{source_dir}/{file_part}" if source_dir else file_part
            if joined in contracts:
                target_file = joined
            else:
                raise ValueError(f"无法解析 $ref（不在唯一源内）: {ref}")
        doc = contracts[target_file]
    else:
        target_file = source_file
        doc = contracts[source_file]
    schema: dict = doc
    if frag:
        for part in frag.strip("/").split("/"):
            schema = schema[part]
    name = pascal(target_file.replace("schemas/", "").replace(".json", ""))
    if frag and "$defs" in frag:
        name = pascal(frag.strip("/").split("/")[-1])
    return name, schema


def pascal(text: str) -> str:
    if not re.search(r"[-_.]", text):
        # 无分隔符：保留既有驼峰（PlanTodo），首字母小写则抬升（goal → Goal）
        return text if text[0].isupper() else text[0].upper() + text[1:]
    return "".join(p.title() for p in re.split(r"[-_.]", text) if p)


_TS_KEYWORDS = {"interface", "type", "const", "new", "delete", "typeof", "in", "enum", "export"}


def safe_prop(name: str) -> str:
    if not re.fullmatch(r"[A-Za-z_$][A-Za-z0-9_$]*", name) or name in _TS_KEYWORDS:
        return json.dumps(name)
    return name


def ts_type(schema: dict, source_file: str, contracts: dict[str, dict], indent: str = "") -> str:
    if "$ref" in schema:
        name, target = resolve_ref(schema["$ref"], source_file, contracts)
        frag = schema["$ref"].split("#", 1)[1] if "#" in schema["$ref"] else ""
        if "/properties/" in frag:
            # 审计修复：指向某个属性的 JSON Pointer（…/properties/name）没有对应的具名类型，
            # 原实现输出不存在的类型名（如 Name），vue-tsc 报 TS2304。这里内联目标类型。
            target_file = schema["$ref"].split("#", 1)[0] or source_file
            return ts_type(target, target_file if target_file in contracts else source_file,
                           contracts, indent)
        return name
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    t = schema.get("type")
    if isinstance(t, list):
        return " | ".join(ts_type({**schema, "type": item}, source_file, contracts) for item in t)
    if t == "null":
        return "null"
    if t == "string":
        return "string"
    if t == "number" or t == "integer":
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "array":
        items = schema.get("items") or {}
        return f"Array<{ts_type(items, source_file, contracts)}>"
    if t == "object":
        return "Record<string, unknown>" if "properties" not in schema else emit_inline_object(
            schema, source_file, contracts, indent)
    return "unknown"


def emit_inline_object(schema: dict, source_file: str, contracts: dict[str, dict], indent: str) -> str:
    pad = indent + "  "
    lines = ["{"]
    props = schema.get("properties") or {}
    required = set(schema.get("required") or [])
    for name, sub in props.items():
        opt = "" if name in required else "?"
        lines.append(f"{pad}{safe_prop(name)}{opt}: {ts_type(sub, source_file, contracts, pad)};")
    if schema.get("additionalProperties") is True:
        lines.append(f"{pad}[key: string]: unknown;")
    lines.append(f"{indent}}}")
    return "\n".join(lines)


def emit_schema(name: str, schema: dict, source_file: str, contracts: dict[str, dict], out: list[str]) -> None:
    if "enum" in schema and schema.get("type") == "string":
        out.append(f"export type {name} =")
        for v in schema["enum"]:
            out.append(f"  | {json.dumps(v)}")
        out.append("")
        return
    if schema.get("type") == "object" or "properties" in schema:
        out.append(f"export interface {name} {{")
        props = schema.get("properties") or {}
        required = set(schema.get("required") or [])
        for prop, sub in props.items():
            opt = "" if prop in required else "?"
            out.append(f"  {safe_prop(prop)}{opt}: {ts_type(sub, source_file, contracts, '  ')};")
        if schema.get("additionalProperties") is True:
            out.append("  [key: string]: unknown;")
        out.append("}")
        out.append("")
        return
    # 纯别名（string/number 等）
    out.append(f"export type {name} = {ts_type(schema, source_file, contracts)};")
    out.append("")


def endpoint_name(endpoint_id: str) -> str:
    parts = re.split(r"[.\-]", endpoint_id)
    return "".join(pascal(p) for p in parts)


def emit_api(contracts: dict[str, dict], out: list[str]) -> None:
    api = contracts["api.json"]
    out.append("/* ---------------- API 端点类型（api.json） ---------------- */")
    out.append("")
    fleet_toml = api.get("$defs", {}).get("FleetToml")
    if fleet_toml:
        emit_schema("FleetToml", fleet_toml, "api.json", contracts, out)
    for ep in api.get("endpoints", []):
        base = endpoint_name(ep["id"])
        request = ep.get("request")
        if isinstance(request, dict) and "$ref" not in request:
            emit_schema(f"{base}Request", request, "api.json", contracts, out)
        response = ep.get("response")
        if isinstance(response, dict):
            emit_schema(f"{base}Response", response, "api.json", contracts, out)
        query = ep.get("query")
        if isinstance(query, dict):
            props = {k: {"type": "string"} for k in query}
            emit_schema(f"{base}Query", {"type": "object", "properties": props}, "api.json", contracts, out)


def generate(contracts: dict[str, dict]) -> str:
    out: list[str] = [GENERATED_HEADER, ""]

    out.append("/* ---------------- 共享 DTO（schemas/*.json） ---------------- */")
    out.append("")
    for rel, doc in contracts.items():
        if not rel.startswith("schemas/"):
            continue
        name = pascal(rel.replace("schemas/", "").replace(".json", ""))
        defs = doc.get("$defs") or {}
        if name == "Plan":
            # plan.json 的 $defs.PlanTodo 先出（被 Plan 引用）
            if "PlanTodo" in defs:
                emit_schema("PlanTodo", defs["PlanTodo"], rel, contracts, out)
        for def_name, sub in defs.items():
            if name == "Plan" and def_name == "PlanTodo":
                continue
            emit_schema(def_name, sub, rel, contracts, out)
        if name != "Plan":
            emit_schema(name, doc, rel, contracts, out)

    out.append("/* ---------------- 契约文件顶层类型 ---------------- */")
    out.append("")
    for rel in ("identity.json", "resources.json", "events.json", "ux-states.json", "errors.json"):
        doc = contracts.get(rel)
        if not doc:
            continue
        name = pascal(rel.replace(".json", ""))
        defs = doc.get("$defs") or {}
        for def_name, sub in defs.items():
            emit_schema(def_name, sub, rel, contracts, out)

    emit_api(contracts, out)

    out.append("/* ---------------- 旧链路类型（未经契约收敛，见 types.legacy.ts） ---------------- */")
    out.append(_LEGACY_REEXPORT)
    out.append("")
    return "\n".join(out)


def check_refs(contracts: dict[str, dict]) -> list[str]:
    errors: list[str] = []

    def walk(node: object, source: str) -> None:
        if isinstance(node, dict):
            if "$ref" in node and isinstance(node["$ref"], str):
                try:
                    resolve_ref(node["$ref"], source, contracts)
                except (ValueError, KeyError) as exc:
                    errors.append(f"{source}: {node['$ref']} -> {exc}")
            for value in node.values():
                walk(value, source)
        elif isinstance(node, list):
            for item in node:
                walk(item, source)

    for rel, doc in contracts.items():
        walk(doc, rel)
    return errors


def main() -> int:
    parser = argparse.ArgumentParser(description="契约唯一源 → types.ts 生成器")
    parser.add_argument("--check", action="store_true", help="校验生成物与提交一致（不改写）")
    parser.add_argument("--contracts-dir", default=None, help="覆盖唯一源目录（测试用）")
    args = parser.parse_args()

    global CONTRACTS
    if args.contracts_dir:
        CONTRACTS = Path(args.contracts_dir).resolve()

    contracts = load_contracts()
    ref_errors = check_refs(contracts)
    if ref_errors:
        for err in ref_errors:
            print(f"$ref 解析失败: {err}", file=sys.stderr)
        return 2

    content = generate(contracts)
    if args.check:
        current = OUT_FILE.read_text(encoding="utf-8") if OUT_FILE.exists() else ""
        if current != content:
            print(f"types.ts 与契约不一致：{OUT_FILE}", file=sys.stderr)
            print("运行 python scripts/contracts_gen.py 重新生成", file=sys.stderr)
            return 1
        print("OK types.ts 与契约唯一源一致")
        return 0

    OUT_FILE.write_text(content, encoding="utf-8")
    print(f"written {OUT_FILE} ({len(content)} chars)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
